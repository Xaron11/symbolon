//! The command set and its TypeScript bindings (`ui/src/lib/api/bindings.ts`, committed).

use tauri_specta::{Builder, collect_commands};

use crate::commands::locations;

/// Every command the frontend can call.
pub(crate) fn builder() -> Builder<tauri::Wry> {
    Builder::new().commands(collect_commands![
        locations::locations_list,
        locations::location_add,
        locations::location_rename,
        locations::location_remove,
        locations::location_set_hash_policy,
        locations::location_follow_move,
        locations::location_stats,
        locations::devices_list,
    ])
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use specta_typescript::Typescript;

    use super::*;

    /// Where the bindings live, relative to this crate.
    const BINDINGS: &str = "ui/src/lib/api/bindings.ts";

    const HEADER: &str =
        "// Generated by symbolon-app (tauri-specta). Run `just bindings`; do not edit.";

    fn export(path: &Path) {
        builder()
            .export(Typescript::default().header(HEADER), path)
            .unwrap();
    }

    fn committed() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS)
    }

    #[test]
    fn bindings_are_current() {
        let dir = tempfile::tempdir().unwrap();
        let fresh = dir.path().join("bindings.ts");
        export(&fresh);
        let fresh = std::fs::read_to_string(fresh).unwrap();
        let committed = std::fs::read_to_string(committed()).unwrap_or_default();
        assert!(
            fresh == committed,
            "{BINDINGS} is out of date; run `just bindings`"
        );
    }

    /// Rewrites the committed bindings (`just bindings`).
    #[test]
    #[ignore = "writes the committed bindings; run with `just bindings`"]
    fn write() {
        export(&committed());
    }
}
