// Writes the book's keyboard page from the keymap, so docs and behaviour cannot drift.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { formatKey, KEYMAP, type KeyContext } from '../src/lib/keyboard/keymap.ts';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');

/** The keyboard page in the book; committed, and checked to stay current. */
export const DOCS_PATH = path.join(REPO, 'docs/design/keyboard.md');

const TITLES: Record<KeyContext, string> = {
	global: 'Everywhere',
	list: 'In tables and trees'
};

/** The keyboard page's Markdown, formatted with the repository's Prettier settings. */
export async function keymapMarkdown(): Promise<string> {
	const sections = (Object.keys(TITLES) as KeyContext[]).map((context) => {
		const rows = KEYMAP.filter((b) => b.context === context)
			.map((b) => `| ${b.keys.map((k) => `\`${formatKey(k)}\``).join(', ')} | ${b.description} |`)
			.join('\n');
		return `## ${TITLES[context]}\n\n| Keys | Action |\n| --- | --- |\n${rows}\n`;
	});
	const text = `# Keyboard

<!-- Generated by crates/symbolon-app/ui/scripts/build-keymap-doc.ts from src/lib/keyboard/keymap.ts; run \`pnpm keymap-doc\` instead of editing. -->

Everything works from the keyboard. Standard keys and vi-style keys work side by side; there is no separate mode. \`Ctrl\` also means the Command key on macOS. Sequences such as \`g l\` are typed one key after the other, within a second.

Single-letter keys and sequences never act while text is being typed (in a field, the command palette, or during IME composition); chords with Ctrl or Alt still do. Press \`?\` for this list in the app.

${sections.join('\n')}`;
	const options = (await resolveConfig(DOCS_PATH)) ?? {};
	return format(text, { ...options, parser: 'markdown' });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(DOCS_PATH, await keymapMarkdown());
}
