// Builds the design tokens in `design/tokens/` (DTCG JSON) into CSS variables, a typed TS module
// and the book's token reference. Primitives are only resolved here, never emitted.
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import StyleDictionary from 'style-dictionary';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
const TOKENS = path.join(REPO, 'design/tokens');

/** Where the generated CSS and TS go inside the UI package. */
export const OUT_DIR = path.join(REPO, 'crates/symbolon-app/ui/src/lib/design/generated');
/** The book page listing every token; committed, and checked to stay current. */
export const DOCS_PATH = path.join(REPO, 'docs/design/tokens.md');

type Theme = 'light' | 'dark';
const THEMES: readonly Theme[] = ['light', 'dark'];

interface Token {
	name: string;
	value: string;
	description: string;
}

interface Resolved {
	scale: Token[];
	component: Token[];
	themes: Record<Theme, Token[]>;
}

function cssValue(value: unknown, type: string | undefined): string {
	if (Array.isArray(value)) {
		return type === 'cubicBezier'
			? `cubic-bezier(${value.join(', ')})`
			: value.map((family) => quoteFont(String(family))).join(', ');
	}
	if (typeof value === 'number' || typeof value === 'string') return String(value);
	throw new TypeError(`unsupported token value ${JSON.stringify(value)}`);
}

/** Generic families stay bare; named families are quoted. */
function quoteFont(family: string): string {
	return ['system-ui', 'sans-serif', 'serif', 'monospace', 'ui-monospace'].includes(family)
		? family
		: `'${family}'`;
}

async function resolve(theme: Theme): Promise<Resolved & { theme: Token[] }> {
	const sd = new StyleDictionary({
		source: [
			path.join(TOKENS, 'primitive/*.json'),
			path.join(TOKENS, 'semantic/scale.json'),
			path.join(TOKENS, `semantic/${theme}.json`),
			path.join(TOKENS, 'component.json')
		],
		usesDtcg: true,
		log: { verbosity: 'silent' },
		platforms: { tokens: {} }
	});
	const { allTokens } = await sd.getPlatformTokens('tokens');
	const scale: Token[] = [];
	const component: Token[] = [];
	const themed: Token[] = [];
	for (const token of allTokens) {
		const file = path.relative(TOKENS, token.filePath);
		const entry: Token = {
			name: token.path.join('.'),
			value: cssValue(token.$value, token.$type),
			description: token.$description ?? ''
		};
		if (file.startsWith('primitive')) continue;
		if (file === 'component.json') component.push(entry);
		else if (file === 'semantic/scale.json') scale.push(entry);
		else themed.push(entry);
	}
	return { scale, component, theme: themed, themes: { light: [], dark: [] } };
}

async function resolveAll(): Promise<Resolved> {
	const [light, dark] = (await Promise.all(THEMES.map(resolve))) as [
		Awaited<ReturnType<typeof resolve>>,
		Awaited<ReturnType<typeof resolve>>
	];
	return {
		scale: light.scale,
		component: light.component,
		themes: { light: light.theme, dark: dark.theme }
	};
}

const cssName = (name: string) => `--sy-${name.replaceAll('.', '-')}`;
const declarations = (tokens: Token[], indent: string) =>
	tokens.map((t) => `${indent}${cssName(t.name)}: ${t.value};`).join('\n');

function css({ scale, component, themes }: Resolved): string {
	// Theme blocks also match any element with data-theme, so a subtree (the gallery's side by
	// side views) can show another theme than the page.
	return `/* Generated by scripts/build-tokens.ts from design/tokens/; do not edit. */
:root {
${declarations([...scale, ...component], '\t')}
}

:root,
[data-theme='light'] {
	color-scheme: light;
${declarations(themes.light, '\t')}
}

@media (prefers-color-scheme: dark) {
	:root:not([data-theme='light']) {
		color-scheme: dark;
${declarations(themes.dark, '\t\t')}
	}
}

[data-theme='dark'] {
	color-scheme: dark;
${declarations(themes.dark, '\t')}
}
`;
}

const record = (tokens: Token[], indent: string) =>
	`{\n${tokens.map((t) => `${indent}\t${JSON.stringify(t.name)}: ${JSON.stringify(t.value)}`).join(',\n')}\n${indent}}`;
const union = (tokens: Token[]) => tokens.map((t) => `\n\t| ${JSON.stringify(t.name)}`).join('');

function ts({ scale, component, themes }: Resolved): string {
	const semantic = (theme: Theme) => [...scale, ...themes[theme]];
	return `// Generated by scripts/build-tokens.ts from design/tokens/; do not edit.

/** A color theme. */
export type ThemeName = 'light' | 'dark';

/** Every semantic token, by dotted name. */
export type SemanticToken =${union(semantic('light'))};

/** Every component token, by dotted name. */
export type ComponentToken =${union(component)};

/** Resolved semantic token values per theme, for code that cannot read CSS variables. */
export const themes: Readonly<Record<ThemeName, Readonly<Record<SemanticToken, string>>>> = {
	light: ${record(semantic('light'), '\t')},
	dark: ${record(semantic('dark'), '\t')}
};

/** Resolved component token values (the same in every theme). */
export const component: Readonly<Record<ComponentToken, string>> = ${record(component, '')};
`;
}

function markdown({ scale, component, themes }: Resolved): string {
	const dark = new Map(themes.dark.map((t) => [t.name, t.value]));
	const code = (s: string) => (s ? `\`${s.replaceAll('|', '\\|')}\`` : '');
	const themeRows = themes.light
		.map(
			(t) =>
				`| ${code(cssName(t.name))} | ${code(t.value)} | ${code(dark.get(t.name) ?? '')} | ${t.description} |`
		)
		.join('\n');
	const valueRows = (tokens: Token[]) =>
		tokens
			.map((t) => `| ${code(cssName(t.name))} | ${code(t.value)} | ${t.description} |`)
			.join('\n');
	return `# Design tokens

<!-- Generated by crates/symbolon-app/ui/scripts/build-tokens.ts from design/tokens/; run \`pnpm tokens\` instead of editing. -->

Every value the interface uses, as CSS custom properties. The source is platform-neutral [DTCG](https://www.designtokens.org/) JSON in \`design/tokens/\`: primitives (raw color ramps, never used directly), semantic tokens (meaning, one file per theme plus theme-independent scales) and component tokens (sizes of specific parts). See [Design system](index.md) for the rules.

## Theme colors and shadows

| Variable | Light | Dark | Purpose |
| --- | --- | --- | --- |
${themeRows}

## Scales

| Variable | Value | Purpose |
| --- | --- | --- |
${valueRows(scale)}

## Component sizes

| Variable | Value | Purpose |
| --- | --- | --- |
${valueRows(component)}
`;
}

/** Builds \`tokens.css\` and \`tokens.ts\` into \`outDir\` and the token reference into \`docsPath\`. */
export async function buildTokens(outDir: string, docsPath: string): Promise<void> {
	const resolved = await resolveAll();
	mkdirSync(outDir, { recursive: true });
	writeFileSync(path.join(outDir, 'tokens.css'), css(resolved));
	writeFileSync(path.join(outDir, 'tokens.ts'), ts(resolved));
	const options = (await resolveConfig(DOCS_PATH)) ?? {};
	mkdirSync(path.dirname(docsPath), { recursive: true });
	writeFileSync(docsPath, await format(markdown(resolved), { ...options, parser: 'markdown' }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	await buildTokens(OUT_DIR, DOCS_PATH);
}
